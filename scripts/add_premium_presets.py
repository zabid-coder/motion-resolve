def main():
    os.makedirs(STYLES_DIR, exist_ok=True)
    added = 0
    tiered = 0
    for preset in PREMIUM_PRESETS:
        path = os.path.join(STYLES_DIR, preset["id"] + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(preset, f, indent=4, ensure_ascii=False)
        added += 1

    # Assign tiers to existing presets (never downgrade user files without map entry)
    for fname in sorted(os.listdir(STYLES_DIR)):
        if not fname.endswith(".json") or fname.startswith("."):
            continue
        pid = os.path.splitext(fname)[0]
        path = os.path.join(STYLES_DIR, fname)
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            continue
        if not isinstance(data, dict):
            continue
        target_tier = EXISTING_TIERS.get(pid) or data.get("tier") or "free"
        if data.get("tier") != target_tier:
            data["tier"] = target_tier
            with open(path, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=4, ensure_ascii=False)
            tiered += 1

    print(f"[PremiumPack] Wrote {added} premium/pro presets; tiered {tiered} existing presets.")


if __name__ == "__main__":
    main()
