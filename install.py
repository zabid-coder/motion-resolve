#!/usr/bin/env python
"""
CaptionForge for Resolve / Motion Resolve - Automated Cross-Platform Installer
Installs Motion Resolve into DaVinci Resolve Studio on macOS and Windows,
creating both Python and native Lua launchers for 100% launch reliability.
"""

import os
import sys
import platform
import shutil
from core.paths import get_scripts_comp_dir, get_scripts_edit_dir, get_app_dir, get_resolve_support_dir

def install():
    print("=" * 60)
    print(" MOTION RESOLVE FOR DAVINCI RESOLVE - Studio Installer")
    print(f" Platform: {platform.system()} ({platform.machine()})")
    print("=" * 60)

    app_dir = get_app_dir()
    targets = [
        # User Support Directory (macOS / Windows Local)
        get_scripts_comp_dir(),
        get_scripts_edit_dir(),
        os.path.join(get_resolve_support_dir(), "Fusion", "Scripts", "Utility"),
        # Global ProgramData Directory (Windows System-Wide / All Pages)
        os.path.join(os.environ.get("PROGRAMDATA", r"C:\ProgramData"), "Blackmagic Design", "DaVinci Resolve", "Fusion", "Scripts", "Utility"),
        os.path.join(os.environ.get("PROGRAMDATA", r"C:\ProgramData"), "Blackmagic Design", "DaVinci Resolve", "Fusion", "Scripts", "Comp"),
        os.path.join(os.environ.get("PROGRAMDATA", r"C:\ProgramData"), "Blackmagic Design", "DaVinci Resolve", "Fusion", "Scripts", "Edit"),
    ]

    bat_escaped = os.path.join(app_dir, "Launch Motion Resolve.bat").replace("\\", "\\\\")

    py_launcher_content = f'''#!/usr/bin/env python
# Motion Resolve Launcher generated by install.py
import sys
import os
import subprocess

APP_DIR = r"{app_dir}"
BAT_PATH = r"{app_dir}\\Launch Motion Resolve.bat"

if sys.platform == "win32":
    # Break away from DaVinci Resolve Job Object via WMI process creation
    ps_cmd = "(Get-CimClass Win32_Process | Invoke-CimMethod -MethodName Create -Arguments @{{CommandLine='cmd.exe /c \\"" + BAT_PATH + "\\"\'}})"
    try:
        subprocess.run(["powershell", "-NoProfile", "-WindowStyle", "Hidden", "-Command", ps_cmd], check=False, creationflags=0x08000000)
        print("[Motion Resolve] Companion panel launched successfully beside DaVinci Resolve!")
    except Exception as e:
        os.system(f'start "" "{{BAT_PATH}}"')
else:
    from core.paths import find_system_python
    python_bin = find_system_python()
    main_script = os.path.join(APP_DIR, "main.py")
    env = os.environ.copy()
    env["PYTHONPATH"] = APP_DIR + (os.pathsep + env["PYTHONPATH"] if "PYTHONPATH" in env else "")
    subprocess.Popen([python_bin, main_script], start_new_session=True, cwd=APP_DIR, env=env)
    print("[Motion Resolve] Companion panel launched successfully beside DaVinci Resolve!")
'''

    lua_launcher_content = f'''-- Motion Resolve Universal Native Launcher
local bat = "{bat_escaped}"
local ps_cmd = 'powershell -NoProfile -WindowStyle Hidden -Command "(Get-CimClass Win32_Process | Invoke-CimMethod -MethodName Create -Arguments @{{CommandLine=\\\'cmd.exe /c \\"' .. bat .. '\\"\\\'}})"'
os.execute(ps_cmd)
print("[Motion Resolve] Companion panel launched successfully beside DaVinci Resolve!")
'''

    installed_paths = []
    for target_dir in targets:
        try:
            os.makedirs(target_dir, exist_ok=True)
            for name_prefix in ["Motion Resolve", "MotionResolve", "CaptionForge"]:
                # Install Python launcher
                dest_py = os.path.join(target_dir, f"{name_prefix}.py")
                with open(dest_py, "w", encoding="utf-8") as f:
                    f.write(py_launcher_content)
                installed_paths.append(dest_py)

                # Install native Lua launcher
                dest_lua = os.path.join(target_dir, f"{name_prefix}.lua")
                with open(dest_lua, "w", encoding="utf-8") as f:
                    f.write(lua_launcher_content)
                installed_paths.append(dest_lua)

                print(f"[OK] Installed launchers to: {target_dir} ({name_prefix})")
        except Exception as e:
            print(f"[Warning] Could not install to {target_dir}: {e}")

    # Create Desktop shortcut for instant 1-click access
    desktop_dir = os.path.join(os.path.expanduser("~"), "Desktop")
    if os.path.exists(desktop_dir):
        desktop_bat = os.path.join(desktop_dir, "Launch Motion Resolve.bat")
        src_bat = os.path.join(app_dir, "Launch Motion Resolve.bat")
        try:
            shutil.copy(src_bat, desktop_bat)
            print(f"[OK] Desktop shortcut created: {desktop_bat}")
        except Exception:
            pass

    if installed_paths:
        print("\n" + "=" * 60)
        print(" SUCCESS! Motion Resolve is now installed in DaVinci Resolve!")
        print(" To launch it:")
        print("   1. Open DaVinci Resolve Studio")
        print("   2. Top menu: Workspace > Scripts > Motion Resolve")
        print("   OR double-click 'Launch Motion Resolve.bat' on your Desktop!")
        print("=" * 60)
        return True
    return False

if __name__ == "__main__":
    install()
