class StyleManager:
    """Manages preset files and catalogs."""

    def __init__(self, presets_dir=None):
        self.builtin_dir = os.path.join(get_app_dir(), "data", "styles")
        self.presets_dir = presets_dir or get_user_presets_dir()
        self.ensure_default_presets()

    def ensure_default_presets(self):
        """Write default preset files if presets folder is empty and writable."""
        target_dir = self.builtin_dir if (os.path.exists(self.builtin_dir) and os.access(self.builtin_dir, os.W_OK)) else self.presets_dir
        try:
            os.makedirs(target_dir, exist_ok=True)
        except Exception:
            target_dir = self.presets_dir
            os.makedirs(target_dir, exist_ok=True)

        for preset in DEFAULT_PRESETS:
            path = os.path.join(target_dir, f"{preset['id']}.json")
            if not os.path.exists(path):
                try:
                    with open(path, "w", encoding="utf-8") as f:
                        json.dump(preset, f, indent=4)
                except Exception as e:
                    print(f"[Motion Resolve] Error writing default preset {preset['id']}: {e}")

    def get_presets(self):
        """Return list of all preset dictionaries sorted by name, loading built-in styles and overlaying user presets."""
        presets_by_id = {}

        # 1. Load built-in presets from data/styles/
        dirs_to_scan = []
        if os.path.exists(self.builtin_dir):
            dirs_to_scan.append(self.builtin_dir)
        if os.path.abspath(self.presets_dir) not in [os.path.abspath(d) for d in dirs_to_scan] and os.path.exists(self.presets_dir):
            dirs_to_scan.append(self.presets_dir)

        for pdir in dirs_to_scan:
            for fname in os.listdir(pdir):
                if fname.endswith(".json") and not fname.startswith("."):
                    path = os.path.join(pdir, fname)
                    try:
                        with open(path, "r", encoding="utf-8") as f:
                            data = json.load(f)
                            if isinstance(data, dict):
                                pid = data.get("id") or os.path.splitext(fname)[0]
                                data["id"] = pid
                                data["_path"] = path
                                presets_by_id[pid] = data
                    except Exception:
                        pass

        # Fallback to in-memory DEFAULT_PRESETS if none on disk
        if not presets_by_id:
            for p in DEFAULT_PRESETS:
                presets_by_id[p["id"]] = dict(p)

        preset_list = list(presets_by_id.values())
        preset_list.sort(key=lambda p: p.get("name", "").lower())
        return preset_list

    def get_all_presets(self):
        """Alias for get_presets for backward compatibility."""
        return self.get_presets()

    def get_preset_by_id(self, preset_id):
        """Retrieve a preset by its unique ID."""
        for p in self.get_presets():
            if p.get("id") == preset_id:
                return p
        return None

    def save_preset(self, preset_id, preset_data):
        """Save or overwrite a preset to JSON."""
        os.makedirs(self.presets_dir, exist_ok=True)
        clean_id = "".join(c for c in preset_id if c.isalnum() or c in ("_", "-")).lower()
        if not clean_id:
            clean_id = "preset_custom"

        preset_data["id"] = clean_id
        path = os.path.join(self.presets_dir, f"{clean_id}.json")
        try:
            with open(path, "w", encoding="utf-8") as f:
                json.dump(preset_data, f, indent=4)
            return True
        except Exception as e:
            print(f"[Motion Resolve] Error saving preset: {e}")
            return False

    def delete_preset(self, preset_id):
        """Delete a custom preset file."""
        path = os.path.join(self.presets_dir, f"{preset_id}.json")
        if os.path.exists(path):
            try:
                os.remove(path)
                return True
            except Exception as e:
                print(f"[Motion Resolve] Error deleting preset: {e}")
                return False
        return False

    def import_preset(self, json_file_path):
        """Import a JSON preset from file into the user catalog."""
        if not os.path.exists(json_file_path):
            return False
        try:
            with open(json_file_path, "r", encoding="utf-8") as f:
                data = json.load(f)
            if not isinstance(data, dict):
                return False

            preset_id = data.get("id") or os.path.splitext(os.path.basename(json_file_path))[0]
            return self.save_preset(preset_id, data)
        except Exception as e:
            print(f"[Motion Resolve] Error importing preset: {e}")
            return False
